#!/usr/bin/env python3
"""The screen-edge HUD's layout table (runtime/core/boot/patches.c, MKW_HUD_POSITION=edges).

Each 1.8.0 layout is found at run time by a signature of its run-time pane tree (patches.c hud_layout_sig): the sum
(mod 2^64) of FNV-1a 64 over (depth byte, name) for the root's size "WxH" at depth 0 and every distinct (depth, pane
name) pair (names of at most 24 bytes) at depths 1 to 3 below its RootPane, where a part pane's children are its part
layout's top panes. Distinct pairs, not every pane: the game clones some panes at run time (RaceInfo_1 holds a second
L_ItemWarning_00 in a race, v180p3b-probe5-tall), which must not change the layout's signature.

  hud_layouts.py signatures TREE > recomp/hud-layouts-180.tsv
      TREE: the names-only pane tree of every layout (one "== NAME WxH" line per layout, then one line per pane:
      two spaces per depth, type, name, "<parent>", and " part=NAME" for a part pane), dumped on the machine that holds
      the game; only layout names, root sizes and signatures are written.
  hud_layouts.py header OUT    writes the C header from the signatures and recomp/hud-classes-180.tsv to OUT
                               (generated C stays out of the repo: tools/build/build.py writes build/obj/rt/hud_layouts.h)
  hud_layouts.py check         fails if a layout has no class, is classified twice, or a class is unknown
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIGS = ROOT / "recomp/hud-layouts-180.tsv"
CLASSES = ROOT / "recomp/hud-classes-180.tsv"
CLASS_SET = ("hud", "hud-auto", "menu", "part", "world", "content", "fullscreen", "split")
M = 2**64 - 1


def fnv(depth, name):
    h = 1469598103934665603
    for b in bytes([depth]) + name.encode()[:24]:
        h = ((h ^ b) * 1099511628211) & M
    return h


def parse_tree(text):
    layouts, cur = {}, None
    for line in text.splitlines():
        m = re.match(r"^== (\S+) (\d+)x(\d+)", line)
        if m:
            cur = layouts[m[1]] = {"size": (int(m[2]), int(m[3])), "panes": []}
            continue
        m = re.match(r"^( *)(\w+) (\S+) <([^>]*)>", line)
        if m and cur is not None:
            part = re.search(r" part=(\S+)", line)
            cur["panes"].append({"depth": len(m[1]) // 2, "type": m[2], "name": m[3], "part": part and part[1]})
    for lay in layouts.values():
        stack = []
        for i, p in enumerate(lay["panes"]):
            del stack[p["depth"]:]
            p["kids"] = []
            if stack:
                lay["panes"][stack[-1]]["kids"].append(i)
            stack.append(i)
    return layouts


def signature(layouts, name):
    pairs = set()

    def walk(lay, idx, depth, seen):
        p = lay["panes"][idx]
        kids = [(lay, k) for k in p["kids"]]
        if p["type"] == "prt" and p["part"] in layouts and p["part"] not in seen:
            part = layouts[p["part"]]
            kids, seen = [(part, k) for k in part["panes"][0]["kids"]], seen | {p["part"]}
        for klay, k in kids:
            pairs.add((depth + 1, klay["panes"][k]["name"][:24]))
            if depth + 1 < 3:
                walk(klay, k, depth + 1, seen)

    walk(layouts[name], 0, 0, frozenset({name}))
    return (fnv(0, "%dx%d" % layouts[name]["size"]) + sum(fnv(d, n) for d, n in pairs)) & M


def read_tsv(path):
    return [line.split("\t") for line in path.read_text().splitlines() if line and not line.startswith("#")]


def table():
    sigs = {name: (size, int(sig, 16)) for name, size, sig in read_tsv(SIGS)}
    classes = {}
    for row in read_tsv(CLASSES):
        name, cls = row[0], row[1]
        if name in classes:
            raise SystemExit(f"{name}: classified twice")
        if cls not in CLASS_SET:
            raise SystemExit(f"{name}: unknown class {cls}")
        classes[name] = cls
    missing, extra = sorted(set(sigs) - set(classes)), sorted(set(classes) - set(sigs))
    if missing or extra:
        raise SystemExit(f"unclassified layouts {missing}, classes for unknown layouts {extra}")
    return [(name, sigs[name][0], sigs[name][1], classes[name]) for name in sorted(sigs)]


def header_text():
    rows = table()
    enum = ", ".join("HUD_CLASS_" + c.upper().replace("-", "_") for c in CLASS_SET)
    out = [
        "// Generated by recomp/hud_layouts.py from recomp/hud-layouts-180.tsv (the 1.8.0 layouts' signatures) and",
        "// recomp/hud-classes-180.tsv (their reviewed classes) by tools/build/build.py. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        f"enum {{ {enum} }};",
        "static const char *const hud_class_names[] = {" + ", ".join(f'"{c}"' for c in CLASS_SET) + "};",
        "typedef struct { uint64_t sig; const char *name; int cls; } HudLayout;",
        "static const HudLayout hud_layouts[] = {",
    ]
    for name, size, sig, cls in rows:
        out.append(f'    {{0x{sig:016x}ull, "{name}", HUD_CLASS_{cls.upper().replace("-", "_")}}},   // {size}')
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv):
    if argv[:1] == ["signatures"] and len(argv) == 2:
        layouts = parse_tree(Path(argv[1]).read_text())
        print("# layout\troot size\tsignature (recomp/hud_layouts.py signatures)")
        for name in sorted(layouts):
            print(f"{name}\t%dx%d\t{signature(layouts, name):016x}" % layouts[name]["size"])
    elif argv[:1] == ["header"] and len(argv) == 2:
        Path(argv[1]).write_text(header_text())
    elif argv == ["check"]:
        print(f"hud layouts: {len(table())} classified")
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
